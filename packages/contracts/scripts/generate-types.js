import { readFile, writeFile } from 'node:fs/promises'
import { compile } from 'json-schema-to-typescript'
import { format, resolveConfig } from 'prettier'

const schema = JSON.parse(await readFile(new URL('../v1/schema.json', import.meta.url)))
const source = {
  title: 'ContractTypes',
  type: 'object',
  properties: Object.fromEntries(
    Object.keys(schema.$defs).map((name) => [name, { $ref: `#/$defs/${name}` }]),
  ),
  required: Object.keys(schema.$defs),
  additionalProperties: false,
  $defs: schema.$defs,
}
const result = await compile(source, 'ContractTypes', {
  bannerComment: '/* Generated by pnpm --filter @world-jigsaw/contracts generate. Do not edit. */',
})
const destination = new URL('../v1/types.d.ts', import.meta.url)
const formatted = await format(result, {
  ...(await resolveConfig(destination)),
  filepath: destination.pathname,
})
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== formatted) {
    console.error(
      'Generated types are out of date; run pnpm --filter @world-jigsaw/contracts generate',
    )
    process.exitCode = 1
  }
} else {
  await writeFile(destination, formatted)
}
